const { Sequelize, DataTypes } = require('sequelize');

// Configura a conexão com o banco de dados PostgreSQL
const sequelize = new Sequelize('myfinance', 'postgres', 'admin', {
  host: 'localhost',
  dialect: 'postgres',
  logging: false, // Desativa logs de SQL no console
});

// Define o modelo da tabela 'Tb_Usuario' - ATUALIZADO
const Usuario = sequelize.define('Usuario', {
  id: {
    type: DataTypes.INTEGER,
    autoIncrement: true, // Equivalente a GENERATED BY DEFAULT AS IDENTITY
    primaryKey: true,
  },
  nome: {
    type: DataTypes.TEXT,
    allowNull: false,
  },
  email: {
    type: DataTypes.TEXT,
    allowNull: false,
    unique: true, // Reflete a constraint UNIQUE
  },
  senha: {
    type: DataTypes.TEXT,
    allowNull: false,
  },
  tipoUsuario: {
    type: DataTypes.INTEGER,
    allowNull: false,
    field: 'tipoUsuario', // Mapeia para a coluna com aspas duplas no banco
  },
  foto: {
    type: DataTypes.TEXT,
    allowNull: true, // Permite NULL como na tabela
  },
}, {
  tableName: 'Tb_Usuario',
  timestamps: false,
});

// Testa a conexão com o banco de dados
sequelize.authenticate()
  .then(() => {
    console.log('Conexão com o banco de dados estabelecida.');
  })
  .catch(error => {
    console.error('Erro ao conectar ao banco de dados:', error);
  });

module.exports = { Usuario, sequelize };